// Writes src/tokenTool/tokenSchemaValidator.js: the token schema (src/tokenTool/token.schema.json,
// a copy of NordvikManager-Addons schemas/token.json) compiled to plain code. Ajv compiles
// schemas with new Function, which the CSP the token editor is served with forbids, so the
// editor uses this precompiled validator instead. Run after changing the schema:
//   node scripts/tokens/build-validator.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import Ajv from "ajv";
import standaloneCode from "ajv/dist/standalone/index.js";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "../..");
export const SCHEMA_FILE = path.join(root, "src/tokenTool/token.schema.json");
export const VALIDATOR_FILE = path.join(root, "src/tokenTool/tokenSchemaValidator.js");

const HEADER = "// Generated by scripts/tokens/build-validator.mjs from token.schema.json. Don't edit.\n/* eslint-disable */\n";

export function validatorSource(schema) {
  const ajv = new Ajv({ allErrors: true, strict: false, code: { source: true, esm: true } });
  return HEADER + standaloneCode(ajv, ajv.compile(schema));
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const schema = JSON.parse(fs.readFileSync(SCHEMA_FILE, "utf8"));
  fs.writeFileSync(VALIDATOR_FILE, validatorSource(schema));
  console.log(`wrote ${path.relative(root, VALIDATOR_FILE)}`);
}
